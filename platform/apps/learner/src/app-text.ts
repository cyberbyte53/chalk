export type AppTextKey = keyof typeof AppText;

/** The copy in the learner's language, with {placeholders} filled in. */
export function say(
  locale: Locale,
  key: AppTextKey,
  values: Readonly<Record<string, string | number>> = {},
): string {
  return AppText[key][locale].replace(/\{(\w+)\}/g, (_, name: string) =>
    String(values[name] ?? ""),
  );
}
