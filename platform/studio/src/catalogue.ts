/**
 * `pnpm catalogue`: library/catalogue.md, the one page that says which props exist, what each
 * shows, what a learner can do on it, and which chapters use it. Generated from the prop
 * definitions and the content tree, so it can't drift; a test fails when it's stale. Read it
 * before writing a new prop: most chapters are better served by one that exists.
 */
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import { type AnyPropDef, BOARD, PropRole } from "@chalk/prop";

type PropRow = {
  type: string;
  describe: string;
  isExplainer: boolean;
  learnerActions: string[];
  usedIn: string[];
};

type PackageRow = { name: string; folder: string; blurb: string; props: PropRow[] };

/** The first paragraph of a README after its title, in one line. */
function blurbOf(readme: string): string {
  const lines = readme.split("\n");
  const start = lines.findIndex((l, i) => i > 0 && l.trim() !== "" && !l.startsWith("#"));
  if (start < 0) return "";
  const para: string[] = [];
  for (let i = start; i < lines.length && lines[i]?.trim() !== ""; i++) para.push(lines[i] ?? "");
  return para.join(" ").replace(/\s+/g, " ").trim();
}

function sourceFiles(dir: string): string[] {
  const out: string[] = [];
  const walk = (d: string) => {
    for (const name of readdirSync(d)) {
      if (name === "node_modules" || name.startsWith(".")) continue;
      const full = join(d, name);
      if (statSync(full).isDirectory()) walk(full);
      else if (/\.tsx?$/.test(name)) out.push(full);
    }
  };
  walk(dir);
  return out;
}

/** Which chapters (book/chapter) name each prop's `<type>Def` in their boards. */
function usesOf(contentDir: string): Map<string, Set<string>> {
  const uses = new Map<string, Set<string>>();
  for (const file of sourceFiles(contentDir)) {
    const rel = file.slice(contentDir.length + 1);
    const chapter = rel.split("/").slice(0, 2).join("/");
    if (!chapter.includes("/")) continue;
    const text = readFileSync(file, "utf8");
    for (const m of text.matchAll(/\b([a-z][A-Za-z0-9]*)Def\b/g)) {
      const type = m[1];
      if (type === undefined) continue;
      if (!uses.has(type)) uses.set(type, new Set());
      uses.get(type)?.add(chapter);
    }
  }
  return uses;
}

/** The rows: one per prop package, with its props and where each is used. */
export function catalogueRows(
  root: string,
  defsByPackage: ReadonlyMap<string, readonly AnyPropDef[]>,
): PackageRow[] {
  const uses = usesOf(join(root, "content"));
  const rows: PackageRow[] = [];
  for (const [name, defs] of [...defsByPackage.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    const folder = `library/props/${name}`;
    let blurb = "";
    try {
      blurb = blurbOf(readFileSync(join(root, folder, "README.md"), "utf8"));
    } catch {}
    const props = defs
      .filter((def) => def.type !== BOARD)
      .map((def) => ({
        type: def.type,
        describe: def.describe,
        isExplainer: def.role === PropRole.Explainer,
        learnerActions: Object.entries(def.actions)
          .filter(([, spec]) => (spec as { byLearner?: boolean }).byLearner === true)
          .map(([action]) => action),
        usedIn: [...(uses.get(def.type) ?? [])].sort(),
      }));
    rows.push({ name, folder, blurb, props });
  }
  return rows;
}

/** The page. */
export function catalogueMarkdown(rows: PackageRow[]): string {
  const out: string[] = [
    "# Prop catalogue",
    "",
    "Generated by `pnpm catalogue` from the prop definitions and the content tree; do not edit. One row per prop: what it shows, what a learner can do on it with a finger, and the chapters that place it. *Explainer* props are the ones Jugnu may bring in to explain.",
    "",
    "Before writing a new prop, look here: a chapter is better served by a prop that exists, reused, than by a new one-off. If one almost fits, extend it (a new action or field) rather than copy it.",
    "",
  ];
  for (const pkg of rows) {
    out.push(`## \`${pkg.name}\` — \`@chalk/prop-${pkg.name}\``, "");
    if (pkg.blurb) out.push(pkg.blurb, "");
    out.push("| Prop | Shows | Learner can | Used in |", "|---|---|---|---|");
    for (const p of pkg.props) {
      const tag = p.isExplainer ? "" : " *(not an explainer)*";
      out.push(
        `| \`${p.type}\`${tag} | ${p.describe.replace(/\|/g, "\\|")} | ${p.learnerActions.map((a) => `\`${a}\``).join(", ") || "—"} | ${p.usedIn.join(", ") || "—"} |`,
      );
    }
    out.push("");
  }
  return `${out.join("\n").trimEnd()}\n`;
}
