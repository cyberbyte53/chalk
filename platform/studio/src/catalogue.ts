/**
 * `pnpm catalogue`: library/catalogue.md, every prop's page (prop-pages.ts) as one file, for a plain
 * checkout without the chalk MCP: which props exist, what each is for, its fields, actions and
 * signals, and which chapters use it. Generated from the prop definitions and the content tree, so
 * it can't drift; a test fails when it's stale. Read it before writing a new prop: most chapters
 * are better served by one that exists.
 */
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import { type PropPage, propPages } from "@chalk/player";
import type { AnyProp } from "@chalk/prop";

type PackageRow = {
  name: string;
  folder: string;
  blurb: string;
  props: (PropPage & { usedIn: string[] })[];
};

/** The first paragraph of a README after its title, in one line. */
function blurbOf(readme: string): string {
  const lines = readme.split("\n");
  const start = lines.findIndex((l, i) => i > 0 && l.trim() !== "" && !l.startsWith("#"));
  if (start < 0) return "";
  const para: string[] = [];
  for (let i = start; i < lines.length && lines[i]?.trim() !== ""; i++) para.push(lines[i] ?? "");
  return para.join(" ").replace(/\s+/g, " ").trim();
}

function sourceFiles(dir: string): string[] {
  const out: string[] = [];
  const walk = (d: string) => {
    for (const name of readdirSync(d)) {
      if (name === "node_modules" || name.startsWith(".")) continue;
      const full = join(d, name);
      if (statSync(full).isDirectory()) walk(full);
      else if (/\.tsx?$/.test(name)) out.push(full);
    }
  };
  walk(dir);
  return out;
}

/** Which chapters (book/chapter) name each prop's `<type>Def` in their boards. */
function usesOf(contentDir: string): Map<string, Set<string>> {
  const uses = new Map<string, Set<string>>();
  for (const file of sourceFiles(contentDir)) {
    const rel = file.slice(contentDir.length + 1);
    const chapter = rel.split("/").slice(0, 2).join("/");
    if (!chapter.includes("/")) continue;
    const text = readFileSync(file, "utf8");
    for (const m of text.matchAll(/\b([a-z][A-Za-z0-9]*)Def\b/g)) {
      const type = m[1];
      if (type === undefined) continue;
      if (!uses.has(type)) uses.set(type, new Set());
      uses.get(type)?.add(chapter);
    }
  }
  return uses;
}

/** The rows: one per prop package, with each prop's page (prop-pages.ts) and where it is used. */
export function catalogueRows(
  root: string,
  defsByPackage: ReadonlyMap<string, readonly AnyProp[]>,
): PackageRow[] {
  const uses = usesOf(join(root, "content"));
  const pages = propPages(defsByPackage);
  return [...new Set(pages.map((p) => p.pkg))].map((name) => {
    const folder = `library/props/${name}`;
    let blurb = "";
    try {
      blurb = blurbOf(readFileSync(join(root, folder, "README.md"), "utf8"));
    } catch {}
    const props = pages
      .filter((p) => p.pkg === name)
      .map((p) => ({ ...p, usedIn: [...(uses.get(p.type) ?? [])].sort() }));
    return { name, folder, blurb, props };
  });
}

const cell = (t: string) => t.replace(/\|/g, "\\|");

/** The page: each package, then each of its props' pages. */
export function catalogueMarkdown(rows: PackageRow[]): string {
  const out: string[] = [
    "# Prop catalogue",
    "",
    "Generated by `pnpm catalogue` from the prop definitions (each prop's contract: its code) and the content tree; do not edit. Each prop: its address, its role, what it is for and its world (its `describe`), its fields, its actions and its signals, and the chapters that place it. A field no action changes is a setting, fixed where a board places the prop; an input is fed by a board's rules. `look` at a prop's address for the same page with a picture and every board that uses it, and `look` at `library/props/` for one line per prop.",
    "",
    "Before writing a new prop, look here: a chapter is better served by a prop that exists, reused, than by a new one-off.",
    "",
  ];
  for (const pkg of rows) {
    out.push(`## \`${pkg.name}\` — \`@chalk/prop-${pkg.name}\``, "");
    if (pkg.blurb) out.push(pkg.blurb, "");
    for (const p of pkg.props) {
      out.push(
        `### \`${p.type}\` · ${p.role}`,
        "",
        `\`${p.address}\` · used in ${p.usedIn.join(", ") || "no chapter yet"}`,
        "",
        p.describe,
        "",
        "| Field | Takes | |",
        "|---|---|---|",
        ...p.fields.map(
          (f) =>
            `| \`${f.name}\` | ${cell(f.takes)} | ${[
              f.isInput
                ? "input"
                : f.changedBy.length > 0
                  ? `changed by ${f.changedBy.join(", ")}`
                  : "setting",
              f.meaning,
            ]
              .filter(Boolean)
              .map((x) => cell(x as string))
              .join(" · ")} |`,
        ),
        "",
      );
      if (p.actions.length > 0)
        out.push(
          "| Action | Takes | |",
          "|---|---|---|",
          ...p.actions.map(
            (a) =>
              `| \`${a.name}\` | ${cell(a.takes) || "—"} | ${a.isByLearner ? "learner · " : ""}${cell(a.describe)} |`,
          ),
          "",
        );
      if (p.signals.length > 0)
        out.push(`Signals: ${p.signals.map((x) => `\`${x}\``).join(", ")}`, "");
      if (p.answers.length > 0)
        out.push(
          `The group answers (each with another part's actions, which change that part): ${p.answers.map((x) => `\`${x}\``).join(", ")}`,
          "",
        );
    }
  }
  return `${out.join("\n").trimEnd()}\n`;
}
